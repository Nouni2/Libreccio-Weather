using System.Xml.Linq;

namespace LibreccioWeather.StringImporter;

internal static class ResxFile
{
    private const string LicenceHeader = """

         This file is part of Libreccio Weather.

         Libreccio Weather is free software: you can redistribute it and/or modify it
         under the terms of the GNU General Public License as published by the Free
         Software Foundation, version 3 of the License.

         Libreccio Weather is distributed in the hope that it will be useful, but
         WITHOUT ANY WARRANTY; without even the implied warranty of MERCHANTABILITY
         or FITNESS FOR A PARTICULAR PURPOSE. See the GNU General Public License for
         more details.

         You should have received a copy of the GNU General Public License along
         with Libreccio Weather. If not, see <https://www.gnu.org/licenses/>.

        """;

    private const string FormsAssembly =
        "System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089";

    /// <summary>
    /// Writes the strings as a .resx file, sorted by key so that a new import only changes the lines that changed.
    /// </summary>
    public static void Write(string path, IReadOnlyDictionary<string, string> strings)
    {
        XNamespace xml = XNamespace.Xml;
        XElement root = new(
            "root",
            Header("resmimetype", "text/microsoft-resx"),
            Header("version", "2.0"),
            Header("reader", "System.Resources.ResXResourceReader, " + FormsAssembly),
            Header("writer", "System.Resources.ResXResourceWriter, " + FormsAssembly));

        foreach ((string key, string value) in strings.OrderBy(pair => pair.Key, StringComparer.Ordinal))
        {
            root.Add(new XElement(
                "data",
                new XAttribute("name", key),
                new XAttribute(xml + "space", "preserve"),
                new XElement("value", value)));
        }

        XDocument document = new(
            new XDeclaration("1.0", "utf-8", null),
            new XComment(LicenceHeader),
            new XComment(" Generated by the string importer. Changes made here are lost at the next import. "),
            root);

        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        document.Save(path);
    }

    private static XElement Header(string name, string value)
    {
        return new XElement("resheader", new XAttribute("name", name), new XElement("value", value));
    }
}
